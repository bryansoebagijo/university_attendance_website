// Writes deploy/mysql/001_create_tables.sql: the complete MySQL schema for a DBA to run by hand.
//   node scripts/build-mysql-sql.mjs
// Generated from the Prisma schema (prisma/schema.prisma → prisma/mysql/schema.prisma), so it always
// matches the code. Re-run it after schema changes and commit the result.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const backend = path.join(here, "..");
const out = path.join(backend, "..", "deploy", "mysql", "001_create_tables.sql");

// Make sure prisma/mysql/schema.prisma is current (the wrapper regenerates it from the main schema).
execFileSync(process.execPath, ["scripts/prisma.mjs", "validate"], { cwd: backend, env: { ...process.env, DB_PROVIDER: "mysql", DATABASE_URL: "" }, stdio: "ignore" });

const prismaBin = path.join(backend, "node_modules", "prisma", "build", "index.js");
let sql = execFileSync(process.execPath, [prismaBin, "migrate", "diff", "--from-empty", "--to-schema-datamodel", "prisma/mysql/schema.prisma", "--script"], {
  cwd: backend,
  encoding: "utf8",
});

const { REQUIRED } = { REQUIRED: Number(/REQUIRED_SCHEMA_VERSION = (\d+)/.exec(readFileSync(path.join(backend, "src", "lib", "schema-version.ts"), "utf8"))[1]) };

const about = {
  User: "Staff accounts of this app. Teachers synced from the campus database have externalId set; name, nip, unit, email and active then come from there. passwordHash is empty until an admin issues a one-time password.",
  UserPhoto: "Profile pictures (JPEG bytes), one per user.",
  WorkSchedule: "Which weekdays a person must be on campus, from effectiveFrom on (days = ISO weekdays, '24' = Tue+Thu). No row = Monday–Friday.",
  AttendanceExemption: "Scheduled days an admin excused (\"Bebaskan\"): not absent, no leave deducted.",
  AdminAction: "Audit log of admin corrections: schedules, attendance added/edited/deleted, exemptions, issued passwords.",
  Location: "QR locations (kiosk screens). qrSecret signs the rotating codes; kioskKeyHash pairs one kiosk.",
  Attendance: "One row per person per day: clock-in/out times, locations, how the QR was read, fixes and admin edits.",
  LeaveRequest: "Annual and sick leave requests and their approval.",
  LeaveAttachment: "Doctor's notes for sick leave (JPEG or PDF bytes, max 5 MB).",
  Holiday: "Public holidays and campus days off (not counted as leave days).",
  SyncRun: "Log of each teacher sync run (nightly or manual) and its results.",
  SchemaVersion: "Installed version of these scripts; the backend refuses to start if it is older than the code needs.",
};
sql = sql.replace(/-- CreateTable\nCREATE TABLE `(\w+)`/g, (m, table) => (about[table] ? `-- ${table}: ${about[table]}\n${m}` : m));

const header = `-- =============================================================================================
-- ISTA Presensi — create all tables (MySQL 8.0+)                         schema version ${REQUIRED}
-- =============================================================================================
-- Run once, as a user that may create tables in this app's database (e.g. root or the DBA):
--   mysql -u root -p ista_absen < 001_create_tables.sql
-- Run 000_create_database_and_user.sql first. Generated by backend/scripts/build-mysql-sql.mjs —
-- do not edit by hand. Later changes come as 002_*.sql, 003_*.sql, … run in order.
-- The app itself only needs SELECT/INSERT/UPDATE/DELETE on these tables.
-- Table names are case-sensitive on Linux: keep them exactly as written.
-- =============================================================================================

SET NAMES utf8mb4;

`;
const footer = `
-- Record the installed script version (checked by the backend at startup).
INSERT INTO \`SchemaVersion\` (\`version\`, \`note\`) VALUES (${REQUIRED}, 'Initial release: attendance, leave, sick leave, schedules, teacher sync');
`;
writeFileSync(out, header + sql.trim() + "\n" + footer);
console.log(`wrote ${path.relative(path.join(backend, ".."), out)}`);
