// Creates YOUR license signing key pair — run once, ever.
//   node tools/license/keygen.mjs [--private <path>]
//
// Private key: stays on your PC (default: ~/.ista-license/ista-license-private.pem). Never commit it,
//   never put it in a release, keep a backup in your password manager. Whoever has it can issue licenses.
// Public key: written into backend/src/lib/license-public-key.ts, so every release can check signatures.
//
// Refuses to overwrite an existing private key: a new key pair makes all issued licenses invalid
// for releases built after the change.
import { generateKeyPairSync } from "node:crypto";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const { values } = parseArgs({ options: { private: { type: "string" }, force: { type: "boolean", default: false } } });
const privatePath = path.resolve(values.private ?? path.join(os.homedir(), ".ista-license", "ista-license-private.pem"));
const repo = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const publicTs = path.join(repo, "backend", "src", "lib", "license-public-key.ts");

if (existsSync(privatePath) && !values.force) {
  console.error(`A private key already exists at ${privatePath}.`);
  console.error("Keep using it. (Replacing it invalidates every license you issued, for new releases.)");
  process.exit(1);
}

const { publicKey, privateKey } = generateKeyPairSync("ed25519");
mkdirSync(path.dirname(privatePath), { recursive: true });
writeFileSync(privatePath, privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600 });
const pem = publicKey.export({ type: "spki", format: "pem" }).toString().trim();
writeFileSync(
  publicTs,
  `// Public half of the license signing key (generated by tools/license/keygen.mjs).
// Safe to publish: it can only CHECK licenses. The private half stays with the developer.
export const LICENSE_PUBLIC_KEY = \`${pem}\`;
`,
);

console.log(`Private key: ${privatePath}`);
console.log("  → back it up now (password manager / encrypted USB). Never commit or share it.");
console.log(`Public key:  ${path.relative(repo, publicTs)} (commit this; it goes into every release)`);
